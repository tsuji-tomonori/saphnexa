import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");

const targets = [
  "apps/api/src/middleware/csrf.ts",
  "apps/api/src/middleware/error.ts",
  "apps/api/src/middleware/origin.ts",
  "apps/api/src/middleware/request-log.ts",
  "apps/api/src/middleware/session.ts",
  "apps/api/src/openapi-document.ts",
  "apps/api/src/zod-openapi-schemas.ts",
  "apps/api/src/hono-openapi-app.ts"
];

for (const sourcePath of targets) {
  const outputPath = sourcePath.replace(/\.ts$/u, ".js");
  const generated = generateMirror(sourcePath);
  if (check) {
    const current = readFileSync(outputPath, "utf8");
    assert(current === generated, `${outputPath} is out of date. Run npm run api:openapi:generate.`);
  } else {
    writeFileSync(outputPath, generated);
  }
}

assertGeneratedSurface();

console.log(check ? "API OpenAPI runtime mirror check passed" : "API OpenAPI runtime mirrors updated");

function generateMirror(sourcePath) {
  const source = readFileSync(sourcePath, "utf8");
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ES2022,
      target: ts.ScriptTarget.ES2022,
      importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
      removeComments: false
    },
    fileName: sourcePath
  }).outputText;
  const body = rewriteRelativeImports(transpiled).trimEnd();
  assert(!body.includes("import type "), `${sourcePath} generated mirror must not keep type-only imports`);
  assert(!body.includes(": HonoRouteDefinition"), `${sourcePath} generated mirror must not keep route type annotations`);
  return `// Generated by tools/generate-api-openapi-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

${body}
`;
}

function rewriteRelativeImports(source) {
  return source.replace(/from "(\.{1,2}\/[^"]+)(?<!\.js)"/gu, 'from "$1.js"');
}

function assertGeneratedSurface() {
  const hono = readFileSync("apps/api/src/hono-openapi-app.js", "utf8");
  for (const token of [
    "errorMiddleware",
    "requestLogMiddleware",
    "originMiddleware",
    "sessionMiddleware",
    "csrfBoundaryMiddleware",
    "API_DISPATCHER_NOT_BOUND",
    "context.json(createErrorResponse(\"API_DISPATCHER_NOT_BOUND\"",
    "), 500)",
    "standardErrorResponse",
    "validateSuccessResponse"
  ]) {
    assert(hono.includes(token), `generated Hono OpenAPI mirror missing ${token}`);
  }
  for (const path of [
    "apps/api/src/openapi-document.js",
    "apps/api/src/zod-openapi-schemas.js",
    "apps/api/src/middleware/csrf.js",
    "apps/api/src/middleware/error.js",
    "apps/api/src/middleware/origin.js",
    "apps/api/src/middleware/request-log.js",
    "apps/api/src/middleware/session.js"
  ]) {
    const body = readFileSync(path, "utf8");
    assert(body.startsWith("// Generated by tools/generate-api-openapi-runtime-mirror.js"), `${path} missing generated header`);
  }
}
