import { readFileSync, writeFileSync } from "node:fs";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");

const targets = [
  {
    label: "Model catalog",
    sourcePath: "packages/model-catalog/src/models.ts",
    outputPath: "packages/model-catalog/src/models.js",
    generate: generateModelsMirror
  },
  {
    label: "Cost estimate",
    sourcePath: "packages/model-catalog/src/cost-estimate.ts",
    outputPath: "packages/model-catalog/src/cost-estimate.js",
    generate: generateCostEstimateMirror
  }
];

for (const target of targets) {
  const source = readFileSync(target.sourcePath, "utf8");
  const generated = target.generate(source, target.sourcePath);
  if (check) {
    const current = readFileSync(target.outputPath, "utf8");
    assert(current === generated, `${target.label} runtime mirror is out of date. Run npm run model-catalog:generate.`);
  } else {
    writeFileSync(target.outputPath, generated);
  }
}

console.log(check ? "model catalog runtime mirror check passed" : "model catalog runtime mirrors updated");

function generateModelsMirror(source, sourcePath) {
  const catalogVersion = extractConstString(source, "catalogVersion");
  const modelIds = extractArray(source, "modelIds");
  const llmModels = extractArray(source, "llmModels");
  assert(countArrayStrings(modelIds) === 3, "modelIds must contain 3 logical model IDs");
  assert((llmModels.match(/model_id:/g) ?? []).length === 3, "llmModels must contain 3 entries");

  return `// Generated by tools/generate-model-catalog-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

export const catalogVersion = ${catalogVersion};

export const modelIds = ${modelIds};

export const llmModels = ${llmModels};
`;
}

function generateCostEstimateMirror(source, sourcePath) {
  const costEstimateSchemaVersion = extractConstString(source, "costEstimateSchemaVersion");
  const localCostEstimate = extractObject(source, "localCostEstimate");
  assert(localCostEstimate.includes("50 DAU"), "localCostEstimate must keep the 50 DAU assumption");
  assert(localCostEstimate.includes("10 questions/user/day"), "localCostEstimate must keep the question volume assumption");

  return `// Generated by tools/generate-model-catalog-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

export const costEstimateSchemaVersion = ${costEstimateSchemaVersion};

export const localCostEstimate = ${localCostEstimate};
`;
}

function extractConstString(source, name) {
  const match = source.match(new RegExp(`export const ${name} = ("[^"]+")`));
  assert(match, `missing ${name} string export`);
  return match[1];
}

function extractArray(source, name) {
  const start = source.indexOf(`export const ${name}`);
  assert(start >= 0, `missing ${name} export`);
  const bracketStart = source.indexOf("[", start);
  assert(bracketStart >= 0, `missing ${name} array`);
  return source.slice(bracketStart, findMatching(source, bracketStart, "[", "]") + 1);
}

function extractObject(source, name) {
  const start = source.indexOf(`export const ${name}`);
  assert(start >= 0, `missing ${name} export`);
  const objectStart = source.indexOf("{", start);
  assert(objectStart >= 0, `missing ${name} object`);
  return source.slice(objectStart, findMatching(source, objectStart, "{", "}") + 1);
}

function countArrayStrings(arraySource) {
  return [...arraySource.matchAll(/"[^"]+"/g)].length;
}

function findMatching(source, start, open, close) {
  let depth = 0;
  let quote = "";
  for (let index = start; index < source.length; index += 1) {
    const char = source[index];
    const previous = source[index - 1];
    if (quote) {
      if (char === quote && previous !== "\\") quote = "";
      continue;
    }
    if (char === "\"" || char === "'" || char === "`") {
      quote = char;
      continue;
    }
    if (char === open) depth += 1;
    if (char === close) depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error(`missing matching ${close}`);
}
