import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");
const sourcePath = "apps/tools-api/src/local-tools-api.ts";
const outputPath = "apps/tools-api/src/local-tools-api.js";

const source = readFileSync(sourcePath, "utf8");
const generated = generateToolsLocalRuntimeMirror(source);

if (check) {
  const current = readFileSync(outputPath, "utf8");
  assert(current === generated, "Tools API local runtime mirror is out of date. Run npm run tools-api:local:generate.");
} else {
  writeFileSync(outputPath, generated);
}

console.log(check ? "Tools API local runtime mirror check passed" : "Tools API local runtime mirror updated");

function generateToolsLocalRuntimeMirror(tsSource) {
  const runtimeSource = ts
    .transpileModule(tsSource, {
      compilerOptions: {
        module: ts.ModuleKind.ES2022,
        target: ts.ScriptTarget.ES2022,
        importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
        removeComments: false
      },
      fileName: sourcePath
    })
    .outputText.replace(/from "(\.{1,2}\/[^"]+)(?<!\.js)"/gu, 'from "$1.js"')
    .trimEnd();

  assert(!runtimeSource.includes("import type "), "generated mirror must not include type-only imports");
  assert(!runtimeSource.includes("ToolInvocationStore"), "generated mirror must not include store type annotations");
  assert(!runtimeSource.includes("ToolOperationId"), "generated mirror must not include operation type annotations");
  assert(runtimeSource.includes("toolContracts.map"), "generated mirror must derive path handlers from tool contracts");
  assert(runtimeSource.includes("TOOL_NOT_FOUND"), "generated mirror must preserve 404 error code");
  for (const operationId of ["kbRetrieve", "bm25Search", "aclCheck", "referenceExpand", "evidencePack", "citationFormat"]) {
    assert(runtimeSource.includes(operationId), `generated mirror missing ${operationId}`);
  }

  return `// Generated by tools/generate-tools-local-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

${runtimeSource}
`;
}
