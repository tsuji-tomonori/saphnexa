import { readFileSync, writeFileSync } from "node:fs";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");
const sourcePath = "packages/rag-core/src/fixture-rag.ts";
const outputPath = "packages/rag-core/src/fixture-rag.js";

const source = readFileSync(sourcePath, "utf8");
const generated = generateRagCoreRuntimeMirror(source);

if (check) {
  const current = readFileSync(outputPath, "utf8");
  assert(current === generated, "RAG core runtime mirror is out of date. Run npm run rag-core:generate.");
} else {
  writeFileSync(outputPath, generated);
}

console.log(check ? "RAG core runtime mirror check passed" : "RAG core runtime mirror updated");

function generateRagCoreRuntimeMirror(tsSource) {
  let runtimeSource = stripExportedInterfaces(tsSource);
  runtimeSource = runtimeSource
    .replace("const localEvidence: RagChunk[] =", "const localEvidence =")
    .replace("export function createFixtureRagAdapter(tools: LocalRagTools)", "export function createFixtureRagAdapter(tools)")
    .replace("answer(input: { question: string; actor: RagActor; run: RagRun }): FixtureRagAnswer", "answer(input)")
    .replace(
      "const retrievalInput: { run_id: string; query: string; retrieval_policy?: RetrievalPolicy } =",
      "const retrievalInput ="
    )
    .replace("export function isPromptInjectionAttempt(question: string)", "export function isPromptInjectionAttempt(question)")
    .replace("export function createLocalTools(store: ToolInvocationStore): LocalRagTools", "export function createLocalTools(store)")
    .replace(
      "function recordTool(store: ToolInvocationStore, tool_name: string, request: { run_id: string } & Record<string, unknown>, responseSummary: Record<string, unknown>)",
      "function recordTool(store, tool_name, request, responseSummary)"
    )
    .replace("function redact(value: unknown): unknown", "function redact(value)")
    .trimEnd();

  assert(!runtimeSource.includes("export interface"), "generated mirror must not include TypeScript interfaces");
  assert(!runtimeSource.includes(": Rag"), "generated mirror must not include RAG type annotations");
  assert(!runtimeSource.includes(": string"), "generated mirror must not include string type annotations");
  assert(!runtimeSource.includes("Record<string, unknown>"), "generated mirror must not include Record type annotations");
  assert(countOccurrences(runtimeSource, "    chunk_id: \"chunk-") === 2, "generated mirror must keep two local evidence chunks");
  assert(runtimeSource.includes("chunk_id: `${node.node_id}-ref`"), "generated mirror must keep reference expansion chunk mapping");
  assert(runtimeSource.includes("chunk_id: chunk.chunk_id"), "generated mirror must keep evidence pack chunk mapping");
  assert(runtimeSource.includes("chunk_id: item.chunk_id"), "generated mirror must keep citation chunk mapping");
  assert(countOccurrences(runtimeSource, "recordTool(store, \"") === 6, "generated mirror must keep six tool invocation records");
  assert(countOccurrences(runtimeSource, "disable citation") === 1, "generated mirror must keep prompt injection catalog");

  return `// Generated by tools/generate-rag-core-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

${runtimeSource}
`;
}

function stripExportedInterfaces(sourceText) {
  let output = "";
  let cursor = 0;
  while (cursor < sourceText.length) {
    const start = sourceText.indexOf("export interface ", cursor);
    if (start < 0) {
      output += sourceText.slice(cursor);
      break;
    }
    output += sourceText.slice(cursor, start);
    const braceStart = sourceText.indexOf("{", start);
    assert(braceStart >= 0, "exported interface missing opening brace");
    const braceEnd = findMatching(sourceText, braceStart, "{", "}");
    cursor = braceEnd + 1;
    while (sourceText[cursor] === "\n") cursor += 1;
  }
  return output;
}

function countOccurrences(sourceText, needle) {
  return sourceText.split(needle).length - 1;
}

function findMatching(sourceText, start, open, close) {
  let depth = 0;
  let quote = "";
  for (let index = start; index < sourceText.length; index += 1) {
    const char = sourceText[index];
    const previous = sourceText[index - 1];
    if (quote) {
      if (char === quote && previous !== "\\") quote = "";
      continue;
    }
    if (char === "\"" || char === "'" || char === "`") {
      quote = char;
      continue;
    }
    if (char === open) depth += 1;
    if (char === close) depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error(`missing matching ${close}`);
}
