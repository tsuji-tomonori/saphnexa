import { readFileSync, writeFileSync } from "node:fs";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");
const sourcePath = "packages/db-schema/src/tables.ts";
const outputPath = "packages/db-schema/src/tables.js";

const source = readFileSync(sourcePath, "utf8");
const generated = generateMirror(source);

if (check) {
  const current = readFileSync(outputPath, "utf8");
  assert(current === generated, "DB tables runtime mirror is out of date. Run npm run db-schema:tables:generate.");
} else {
  writeFileSync(outputPath, generated);
}

console.log(check ? "DB tables runtime mirror check passed" : "DB tables runtime mirror updated");

function generateMirror(sourceText) {
  const requiredTableNames = extractArray(sourceText, "requiredTableNames");
  assert(countArrayStrings(requiredTableNames) === 38, "requiredTableNames must contain 38 DB tables");

  return `// Generated by tools/generate-db-tables-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

export const requiredTableNames = ${requiredTableNames};

export const requiredTables = requiredTableNames;
`;
}

function extractArray(sourceText, name) {
  const start = sourceText.indexOf(`export const ${name}`);
  assert(start >= 0, `missing ${name} export`);
  const bracketStart = sourceText.indexOf("[", start);
  assert(bracketStart >= 0, `missing ${name} array`);
  return sourceText.slice(bracketStart, findMatching(sourceText, bracketStart, "[", "]") + 1);
}

function countArrayStrings(arraySource) {
  return [...arraySource.matchAll(/"[^"]+"/g)].length;
}

function findMatching(sourceText, start, open, close) {
  let depth = 0;
  let quote = "";
  for (let index = start; index < sourceText.length; index += 1) {
    const char = sourceText[index];
    const previous = sourceText[index - 1];
    if (quote) {
      if (char === quote && previous !== "\\") quote = "";
      continue;
    }
    if (char === "\"" || char === "'" || char === "`") {
      quote = char;
      continue;
    }
    if (char === open) depth += 1;
    if (char === close) depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error(`missing matching ${close}`);
}
