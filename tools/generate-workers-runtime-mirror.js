import { readFileSync, writeFileSync } from "node:fs";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");
const sourcePath = "apps/workers/src/event-publisher.ts";
const outputPath = "apps/workers/src/event-publisher.js";

const source = readFileSync(sourcePath, "utf8");
const generated = generateWorkersRuntimeMirror(source);

if (check) {
  const current = readFileSync(outputPath, "utf8");
  assert(current === generated, "Workers runtime mirror is out of date. Run npm run workers:generate.");
} else {
  writeFileSync(outputPath, generated);
}

console.log(check ? "Workers runtime mirror check passed" : "Workers runtime mirror updated");

function generateWorkersRuntimeMirror(tsSource) {
  let runtimeSource = stripExportedInterfaces(tsSource);
  runtimeSource = runtimeSource
    .replace(/\s+as const;/u, ";")
    .replace(
      "export function createLightweightNotification(event: ChatMessageEventForNotification): LightweightNotification",
      "export function createLightweightNotification(event)"
    )
    .replace(
      "export function assertNotificationIsLightweight(notification: LightweightNotification | Record<string, unknown>): boolean",
      "export function assertNotificationIsLightweight(notification)"
    )
    .trimEnd();

  assert(!runtimeSource.includes("export interface"), "generated mirror must not include TypeScript interfaces");
  assert(!runtimeSource.includes(": LightweightNotification"), "generated mirror must not include notification type annotations");
  assert(!runtimeSource.includes(": boolean"), "generated mirror must not include boolean return annotations");
  assert(runtimeSource.includes("export const forbiddenNotificationFields"), "generated mirror must export forbidden fields");
  assert(runtimeSource.includes("export const maxNotificationPayloadBytes = 4096"), "generated mirror must export payload byte limit");
  assert(countOccurrences(runtimeSource, "\"answer_text\"") === 1, "generated mirror must keep answer_text forbidden field once");
  assert(runtimeSource.includes("Buffer.byteLength(serialized, \"utf8\")"), "generated mirror must keep UTF-8 payload sizing");
  assert(runtimeSource.includes("/api/chat-sessions/"), "generated mirror must keep REST detail URL");

  return `// Generated by tools/generate-workers-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

${runtimeSource}
`;
}

function stripExportedInterfaces(sourceText) {
  let output = "";
  let cursor = 0;
  while (cursor < sourceText.length) {
    const start = sourceText.indexOf("export interface ", cursor);
    if (start < 0) {
      output += sourceText.slice(cursor);
      break;
    }
    output += sourceText.slice(cursor, start);
    const braceStart = sourceText.indexOf("{", start);
    assert(braceStart >= 0, "exported interface missing opening brace");
    const braceEnd = findMatching(sourceText, braceStart, "{", "}");
    cursor = braceEnd + 1;
    while (sourceText[cursor] === "\n") cursor += 1;
  }
  return output;
}

function countOccurrences(sourceText, needle) {
  return sourceText.split(needle).length - 1;
}

function findMatching(sourceText, start, open, close) {
  let depth = 0;
  let quote = "";
  for (let index = start; index < sourceText.length; index += 1) {
    const char = sourceText[index];
    const previous = sourceText[index - 1];
    if (quote) {
      if (char === quote && previous !== "\\") quote = "";
      continue;
    }
    if (char === "\"" || char === "'" || char === "`") {
      quote = char;
      continue;
    }
    if (char === open) depth += 1;
    if (char === close) depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error(`missing matching ${close}`);
}
