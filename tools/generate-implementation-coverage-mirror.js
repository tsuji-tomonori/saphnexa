import { readFileSync, writeFileSync } from "node:fs";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");

const targets = [
  {
    label: "API implementation coverage",
    sourcePath: "packages/api-contract/src/implementation-coverage.ts",
    outputPath: "packages/api-contract/src/implementation-coverage.js",
    exportName: "apiImplementationCoverage",
    factoryName: "api",
    helper: `function api(route, schema, usecase, localFixture, production, overrides = {}) {
  const unitTest = overrides.unitTest ?? "planned";
  const localIntegrationTest = overrides.localIntegrationTest ?? (localFixture === "planned" ? "planned" : "implemented");
  const dsqlSmoke = overrides.dsqlSmoke ?? (production === "implemented" ? "planned" : "not_required");
  return {
    route,
    schema,
    usecase,
    localFixture,
    production,
    repository: overrides.repository ?? production,
    domainEvent: overrides.domainEvent ?? "not_required",
    audit: overrides.audit ?? "not_required",
    openApi: "implemented",
    unitTest,
    localIntegrationTest,
    dsqlSmoke,
    explicitPlannedMarker: hasPlanned([
      route,
      schema,
      usecase,
      localFixture,
      production,
      overrides.repository,
      overrides.domainEvent,
      overrides.audit,
      unitTest,
      localIntegrationTest,
      dsqlSmoke
    ])
      ? "present"
      : "not_required",
    ...(overrides.externalReason ? { externalReason: overrides.externalReason } : {})
  };
}`
  },
  {
    label: "Tools implementation coverage",
    sourcePath: "packages/tool-contract/src/implementation-coverage.ts",
    outputPath: "packages/tool-contract/src/implementation-coverage.js",
    exportName: "toolImplementationCoverage",
    factoryName: "tool",
    helper: `function tool(route, schema, usecase, policy, audit, timeout, production) {
  const unitTest = "planned";
  return {
    route,
    schema,
    usecase,
    policy,
    requestValidation: schema,
    responseValidation: schema,
    audit,
    timeout,
    production,
    unitTest,
    explicitPlannedMarker: hasPlanned([route, schema, usecase, policy, audit, timeout, production, unitTest]) ? "present" : "not_required"
  };
}`
  }
];

for (const target of targets) {
  const generated = generateMirror(target);
  if (check) {
    const current = readFileSync(target.outputPath, "utf8");
    assert(current === generated, `${target.label} generated mirror is out of date. Run npm run implementation-coverage:generate.`);
  } else {
    writeFileSync(target.outputPath, generated);
  }
}

console.log(check ? "implementation coverage generated mirror check passed" : "implementation coverage generated mirrors updated");

function generateMirror(target) {
  const source = readFileSync(target.sourcePath, "utf8");
  const entries = extractEntries(source, target.factoryName);
  assert(entries.length > 0, `${target.label} TS source has no entries`);
  return `// Generated by tools/generate-implementation-coverage-mirror.js from ${target.sourcePath}. Do not edit by hand.

export const ${target.exportName} = {
${entries.join(",\n")}
};

${target.helper}

function hasPlanned(values) {
  return values.includes("planned");
}
`;
}

function extractEntries(source, factoryName) {
  const entries = [];
  const entryPattern = new RegExp(`^  ([A-Za-z][A-Za-z0-9]+): ${factoryName}\\((.*)\\),?$`, "gm");
  for (const match of source.matchAll(entryPattern)) {
    entries.push(`  ${match[1]}: ${factoryName}(${match[2]})`);
  }
  return entries;
}
