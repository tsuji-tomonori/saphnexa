import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");
const sourcePath = "apps/agent/src/agent/retrievalPolicy.ts";
const outputPath = "apps/agent/src/rag-agent.js";

const source = readFileSync(sourcePath, "utf8");
const generated = generateAgentPolicyRuntimeMirror(source);

if (check) {
  const current = readFileSync(outputPath, "utf8");
  assert(current === generated, "Agent policy runtime mirror is out of date. Run npm run agent:policy:generate.");
} else {
  writeFileSync(outputPath, generated);
}

console.log(check ? "Agent policy runtime mirror check passed" : "Agent policy runtime mirror updated");

function generateAgentPolicyRuntimeMirror(tsSource) {
  const runtimeSource = ts
    .transpileModule(tsSource, {
      compilerOptions: {
        module: ts.ModuleKind.ES2022,
        target: ts.ScriptTarget.ES2022,
        importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
        removeComments: false
      },
      fileName: sourcePath
    })
    .outputText.trimEnd();

  assert(!runtimeSource.includes("import type "), "generated mirror must not include type-only imports");
  assert(!runtimeSource.includes(": RetrievalPolicy"), "generated mirror must not include retrieval policy annotations");
  assert(runtimeSource.includes("assertRetrievalPolicyNotRelaxed"), "generated mirror must export policy guard");
  assert(runtimeSource.includes("normalizeRetrievalPolicy"), "generated mirror must export policy normalizer");
  assert(runtimeSource.includes("retrieval_policy top_k was relaxed"), "generated mirror must preserve top_k guard");
  assert(runtimeSource.includes("retrieval_policy scope was relaxed"), "generated mirror must preserve ACL scope guard");

  return `// Generated by tools/generate-agent-policy-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

${runtimeSource}
`;
}
