import { writeFileSync, readFileSync } from "node:fs";
import { buildOpenApiDocument } from "../apps/api/src/openapi-document.js";
import { publicApiRoutes } from "../packages/api-contract/src/routes.js";

const outputPath = "packages/api-client/src/generated/operation-types.ts";
const checkOnly = process.argv.includes("--check");
const content = buildOperationTypesSource();

if (checkOnly) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== content) {
    throw new Error(`${outputPath} is out of date. Run node tools/build-api-client-operation-types.js`);
  }
  console.log("API client operation types are up to date");
} else {
  writeFileSync(outputPath, content);
  console.log(`wrote ${outputPath}`);
}

function buildOperationTypesSource() {
  const openApiDocument = buildOpenApiDocument();
  const lines = [
    "/*",
    " * Generated by tools/build-api-client-operation-types.js.",
    " * Do not edit by hand.",
    " */",
    "",
    "export type ApiClientJsonObject = Record<string, unknown>;",
    "export type ApiClientEmptyObject = Record<string, never>;",
    "",
    "export interface ApiClientErrorResponse {",
    "  trace_id: string;",
    "  error_code: string;",
    "  message: string;",
    "  details: ApiClientJsonObject;",
    "}",
    "",
    `export type ApiClientGeneratedOperationId = ${union(publicApiRoutes.map((route) => route.operationId))};`,
    "",
    "export interface ApiClientOperationTypes {"
  ];

  for (const route of publicApiRoutes) {
    const operation = openApiDocument.paths[route.internalPath]?.[route.method.toLowerCase()];
    if (!operation) throw new Error(`OpenAPI document missing ${route.method} ${route.internalPath}`);
    if (operation.operationId !== route.operationId) {
      throw new Error(`OpenAPI operationId mismatch for ${route.id}: ${operation.operationId}`);
    }
    if (operation["x-saphnexa-viewer-path"] !== route.viewerPath) {
      throw new Error(`OpenAPI viewer path mismatch for ${route.id}`);
    }

    lines.push(`  ${route.operationId}: {`);
    lines.push(`    operationId: ${literal(route.operationId)};`);
    lines.push(`    method: ${literal(route.method)};`);
    lines.push(`    viewerPath: ${literal(route.viewerPath)};`);
    lines.push(`    internalPath: ${literal(route.internalPath)};`);
    lines.push(`    roles: ${union(route.roles)};`);
    lines.push(`    csrfRequired: ${route.csrfRequired};`);
    lines.push(`    params: ${paramsType(route.viewerPath)};`);
    lines.push(`    query: ${queryType(route.operationId)};`);
    lines.push(`    requestBody: ${requestBodyType(operation)};`);
    lines.push(`    successStatus: ${route.successStatuses.join(" | ")};`);
    lines.push(`    successResponse: ${successResponseType(route, operation)};`);
    lines.push("    errorResponse: ApiClientErrorResponse;");
    lines.push("  };");
  }

  lines.push("}");
  lines.push("");
  lines.push("export type ApiClientOperationType<T extends ApiClientGeneratedOperationId> = ApiClientOperationTypes[T];");
  lines.push("export type ApiClientOperationRequest<T extends ApiClientGeneratedOperationId> = ApiClientOperationTypes[T][\"requestBody\"];");
  lines.push("export type ApiClientOperationResponse<T extends ApiClientGeneratedOperationId> = ApiClientOperationTypes[T][\"successResponse\"];");

  return `${lines.join("\n")}\n`;
}

function paramsType(path) {
  const params = [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
  if (params.length === 0) return "ApiClientEmptyObject";
  return `{ ${params.map((name) => `${name}: string`).join("; ")} }`;
}

function queryType(operationId) {
  if (operationId === "listMessageEvents") return "{ after_seq?: number }";
  if (operationId === "listMessages") return "{ after_message_id?: string; limit?: number }";
  return "ApiClientEmptyObject";
}

function requestBodyType(operation) {
  const schema = operation.requestBody?.content?.["application/json"]?.schema;
  if (!schema) return "never";
  return schemaToType(schema);
}

function successResponseType(route, operation) {
  if (route.successStatuses.every((status) => status === 204 || status === 302)) return "void";
  const status = route.successStatuses.find((item) => item >= 200 && item < 300 && item !== 204 && item !== 302);
  const schema = status ? operation.responses?.[String(status)]?.content?.["application/json"]?.schema : undefined;
  if (!schema) return "void";
  return schemaToType(schema);
}

function schemaToType(schema) {
  if (schema.$ref === "#/components/schemas/ErrorResponse") return "ApiClientErrorResponse";
  if (Array.isArray(schema.type)) return schema.type.map((item) => schemaToType({ ...schema, type: item })).join(" | ");
  if (Array.isArray(schema.enum) && schema.enum.length > 0) return union(schema.enum);
  if (schema.type === "string") return "string";
  if (schema.type === "null") return "null";
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "array") return `${schemaToType(schema.items || { type: "object", additionalProperties: true })}[]`;
  if (schema.type === "object") return objectSchemaToType(schema);
  return "unknown";
}

function objectSchemaToType(schema) {
  const entries = Object.entries(schema.properties || {});
  if (entries.length === 0) return schema.additionalProperties ? "ApiClientJsonObject" : "ApiClientEmptyObject";
  const required = new Set(schema.required || []);
  const fields = entries.map(([name, fieldSchema]) => `${propertyName(name)}${required.has(name) ? "" : "?"}: ${schemaToType(fieldSchema)}`);
  const base = `{ ${fields.join("; ")} }`;
  return schema.additionalProperties ? `${base} & ApiClientJsonObject` : base;
}

function propertyName(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : literal(name);
}

function union(values) {
  return values.map((value) => literal(value)).join(" | ");
}

function literal(value) {
  return JSON.stringify(value);
}
