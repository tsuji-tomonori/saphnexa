import { readFileSync, writeFileSync } from "node:fs";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");

const targets = [
  {
    label: "Domain index",
    sourcePath: "packages/domain/src/index.ts",
    outputPath: "packages/domain/src/index.js",
    generate: generateDomainIndexMirror
  },
  {
    label: "Domain observability",
    sourcePath: "packages/domain/src/observability.ts",
    outputPath: "packages/domain/src/observability.js",
    generate: generateObservabilityMirror
  }
];

for (const target of targets) {
  const source = readFileSync(target.sourcePath, "utf8");
  const generated = target.generate(source, target.sourcePath);
  if (check) {
    const current = readFileSync(target.outputPath, "utf8");
    assert(current === generated, `${target.label} runtime mirror is out of date. Run npm run domain:generate.`);
  } else {
    writeFileSync(target.outputPath, generated);
  }
}

console.log(check ? "domain runtime mirror check passed" : "domain runtime mirrors updated");

function generateDomainIndexMirror(source, sourcePath) {
  const roles = extractObject(source, "roles");
  const participantRoles = extractObject(source, "participantRoles");
  const statuses = extractObject(source, "statuses");
  const chatEventNames = extractArray(source, "chatEventNames");
  const adminEventNames = extractArray(source, "adminEventNames");
  assert(countArrayStrings(chatEventNames) === 10, "chatEventNames must contain 10 events");
  assert(countArrayStrings(adminEventNames) === 4, "adminEventNames must contain 4 events");

  return `// Generated by tools/generate-domain-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

export const roles = Object.freeze(${roles});

export const participantRoles = Object.freeze(${participantRoles});

export const statuses = Object.freeze(${statuses});

export const chatEventNames = Object.freeze(${chatEventNames});

export const adminEventNames = Object.freeze(${adminEventNames});

export function canReadChat(participant) {
  return participant?.status === statuses.ACTIVE && [participantRoles.OWNER, participantRoles.VIEWER].includes(participant.participant_role);
}

export function canWriteChat(participant) {
  return participant?.status === statuses.ACTIVE && participant.participant_role === participantRoles.OWNER;
}

export function canManageAdmin(user) {
  return user?.role === roles.ADMIN && user?.status === statuses.ACTIVE;
}

export function createErrorResponse(error_code, message, details = {}, trace_id = "trace-local") {
  return { trace_id, error_code, message, details };
}
`;
}

function generateObservabilityMirror(source, sourcePath) {
  const logSchemaRequiredFields = extractArray(source, "logSchemaRequiredFields");
  const requiredMetricCatalog = extractArray(source, "requiredMetricCatalog");
  const requiredAlarmCatalog = extractArray(source, "requiredAlarmCatalog");
  const retentionPolicyCatalog = extractArray(source, "retentionPolicyCatalog");
  assert(countCalls(requiredMetricCatalog, "metric") === 7, "requiredMetricCatalog must contain 7 metrics");
  assert(countCalls(requiredAlarmCatalog, "alarm") === 6, "requiredAlarmCatalog must contain 6 alarms");
  assert(countCalls(retentionPolicyCatalog, "retention") === 7, "retentionPolicyCatalog must contain 7 retention policies");

  return `// Generated by tools/generate-domain-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

export const logSchemaRequiredFields = ${logSchemaRequiredFields};

export const requiredMetricCatalog = ${requiredMetricCatalog};

export const requiredAlarmCatalog = ${requiredAlarmCatalog};

export const retentionPolicyCatalog = ${retentionPolicyCatalog};

export function createLogEvent(input) {
  return {
    timestamp: input.timestamp || "2026-05-27T00:00:00.000Z",
    level: input.level || "INFO",
    service: "saphnexa",
    env: input.env || "local",
    logical_function: input.logical_function,
    trace_id: input.trace_id,
    correlation_id: input.correlation_id || input.trace_id,
    message: input.message,
    attributes: input.attributes || {}
  };
}

export function assertLogSchema(event) {
  for (const field of logSchemaRequiredFields) {
    if (!event[field]) throw new Error(\`log event missing \${field}\`);
  }
  if (!["DEBUG", "INFO", "WARN", "ERROR"].includes(event.level)) throw new Error(\`invalid log level \${event.level}\`);
  if (event.service !== "saphnexa") throw new Error("service must be saphnexa");
  return true;
}

export function assertTracePropagation(events) {
  if (events.length === 0) throw new Error("trace propagation requires events");
  const traceId = events[0].trace_id;
  const correlationId = events[0].correlation_id;
  for (const event of events) {
    assertLogSchema(event);
    if (event.trace_id !== traceId) throw new Error("trace_id was not propagated");
    if (event.correlation_id !== correlationId) throw new Error("correlation_id was not propagated");
  }
  return true;
}

function metric(metric_name, description, unit, acceptance) {
  return { metric_name, description, unit, acceptance, namespace: "Saphnexa/Local" };
}

function alarm(alarm_name, metric_name, comparison_operator, threshold) {
  return { alarm_name, metric_name, comparison_operator, threshold, evaluation_periods: 1, treat_missing_data: "notBreaching" };
}

function retention(resource_name, resource_type, retention_days) {
  return { resource_name, resource_type, retention_days };
}
`;
}

function extractArray(source, name) {
  const start = source.indexOf(`export const ${name}`);
  assert(start >= 0, `missing ${name} export`);
  const bracketStart = source.indexOf("[", start);
  assert(bracketStart >= 0, `missing ${name} array`);
  return stripConstAssertion(source.slice(bracketStart, findMatching(source, bracketStart, "[", "]") + 1));
}

function extractObject(source, name) {
  const start = source.indexOf(`export const ${name}`);
  assert(start >= 0, `missing ${name} export`);
  const objectStart = source.indexOf("{", start);
  assert(objectStart >= 0, `missing ${name} object`);
  return stripConstAssertion(source.slice(objectStart, findMatching(source, objectStart, "{", "}") + 1));
}

function stripConstAssertion(value) {
  return value.replace(/\s+as const\s*$/u, "");
}

function countArrayStrings(arraySource) {
  return [...arraySource.matchAll(/"[^"]+"/g)].length;
}

function countCalls(source, functionName) {
  return [...source.matchAll(new RegExp(`${functionName}\\(`, "g"))].length;
}

function findMatching(source, start, open, close) {
  let depth = 0;
  let quote = "";
  for (let index = start; index < source.length; index += 1) {
    const char = source[index];
    const previous = source[index - 1];
    if (quote) {
      if (char === quote && previous !== "\\") quote = "";
      continue;
    }
    if (char === "\"" || char === "'" || char === "`") {
      quote = char;
      continue;
    }
    if (char === open) depth += 1;
    if (char === close) depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error(`missing matching ${close}`);
}
