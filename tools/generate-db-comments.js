import { mkdirSync, writeFileSync } from "node:fs";
import { metadataTables, sqlQuote } from "./db-metadata-lib.js";

const lines = ["-- Generated by tools/generate-db-comments.js. Do not edit by hand.", ""];
for (const table of metadataTables()) {
  lines.push(`COMMENT ON TABLE ${table.tableName} IS '${sqlQuote(table.description)}';`);
  for (const column of table.columns) {
    lines.push(`COMMENT ON COLUMN ${table.tableName}.${column.name} IS '${sqlQuote(column.description)}';`);
  }
  lines.push("");
}

const body = `${lines.join("\n").trim()}\n`;
mkdirSync("packages/db-migrations/generated", { recursive: true });
mkdirSync("docs/generated/db", { recursive: true });
writeFileSync("packages/db-migrations/generated/schema-comments.sql", body);
writeFileSync("docs/generated/db/schema-comments.sql", body);
console.log(`generated schema comments for ${metadataTables().length} tables`);
