import { readFileSync, writeFileSync } from "node:fs";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");

const targets = [
  {
    label: "API contract",
    sourcePath: "packages/api-contract/src/routes.ts",
    outputPath: "packages/api-contract/src/routes.js",
    generate: generateApiContractMirror
  },
  {
    label: "Tool contract",
    sourcePath: "packages/tool-contract/src/tools.ts",
    outputPath: "packages/tool-contract/src/tools.js",
    generate: generateToolContractMirror
  }
];

for (const target of targets) {
  const source = readFileSync(target.sourcePath, "utf8");
  const generated = target.generate(source, target.sourcePath);
  if (check) {
    const current = readFileSync(target.outputPath, "utf8");
    assert(current === generated, `${target.label} runtime mirror is out of date. Run npm run contract-mirror:generate.`);
  } else {
    writeFileSync(target.outputPath, generated);
  }
}

console.log(check ? "contract runtime mirror check passed" : "contract runtime mirrors updated");

function generateApiContractMirror(source, sourcePath) {
  const apiRouteIds = extractArray(source, "apiRouteIds");
  const apiOperationIds = extractArray(source, "apiOperationIds");
  const errorResponseSchema = extractObject(source, "errorResponseSchema");
  const routeEntries = extractEntries(source, "route");
  assert(routeEntries.length === 40, "API contract TS source must have 40 route entries");

  return `// Generated by tools/generate-contract-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

export const apiRouteIds = ${apiRouteIds};

export const apiOperationIds = ${apiOperationIds};

export const errorResponseSchema = ${errorResponseSchema};

const json = ["application/json"];
const csrf = true;

export const publicApiRoutes = [
${routeEntries.join(",\n")}
];

export function route(id, operationId, method, viewerPath, internalPath, roles, csrfRequired, successStatuses) {
  return {
    id,
    operationId,
    method,
    viewerPath,
    internalPath,
    roles,
    csrfRequired,
    requestContentTypes: method === "GET" || method === "DELETE" ? [] : json,
    responseContentTypes: successStatuses.includes(204) || successStatuses.includes(302) ? [] : json,
    successStatuses,
    errorSchema: errorResponseSchema.name
  };
}

export function assertPublicApiContract() {
  const ids = new Set(publicApiRoutes.map((item) => item.id));
  const operationIds = new Set(publicApiRoutes.map((item) => item.operationId));
  if (publicApiRoutes.length !== 40) throw new Error(\`expected 40 public routes, got \${publicApiRoutes.length}\`);
  if (ids.size !== 40) throw new Error("public API IDs must be unique");
  if (operationIds.size !== 40) throw new Error("public API operationIds must be unique");
  for (const item of publicApiRoutes) {
    if (!apiRouteIds.includes(item.id)) throw new Error(\`\${item.id} is missing from apiRouteIds\`);
    if (!apiOperationIds.includes(item.operationId)) throw new Error(\`\${item.operationId} is missing from apiOperationIds\`);
    if (!item.viewerPath.startsWith("/api/") && !item.viewerPath.startsWith("/auth/")) {
      throw new Error(\`\${item.id} has invalid viewer path \${item.viewerPath}\`);
    }
    if (!item.internalPath.startsWith("/v1/")) throw new Error(\`\${item.id} must map to /v1/*\`);
    if (["POST", "PATCH", "DELETE"].includes(item.method) && item.id !== "API-21" && item.csrfRequired !== true) {
      throw new Error(\`\${item.id} state-changing route must require CSRF\`);
    }
  }
  return true;
}
`;
}

function generateToolContractMirror(source, sourcePath) {
  const toolNames = extractArray(source, "toolNames");
  const toolOperationIds = extractArray(source, "toolOperationIds");
  const toolErrorStatuses = extractArray(source, "toolErrorStatuses");
  const toolEntries = extractEntries(source, "tool");
  assert(toolEntries.length === 6, "Tool contract TS source must have 6 tool entries");

  return `// Generated by tools/generate-contract-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

export const toolNames = ${toolNames};

export const toolOperationIds = ${toolOperationIds};

export const toolErrorStatuses = ${toolErrorStatuses};

export const toolContracts = [
${toolEntries.join(",\n")}
];

function tool(toolName, operationId, path, requestSchema, responseSchema, scope, timeoutMs) {
  return {
    toolName,
    operationId,
    method: "POST",
    path,
    requestSchema,
    responseSchema,
    auth: "agentcore-gateway-outbound",
    csrfRequired: false,
    scope,
    timeoutMs,
    auditTable: "tool_invocations",
    successStatuses: [200],
    errorStatuses: [...toolErrorStatuses]
  };
}

export function assertToolContract() {
  const names = new Set(toolContracts.map((item) => item.toolName));
  const operationIds = new Set(toolContracts.map((item) => item.operationId));
  if (toolContracts.length !== 6) throw new Error(\`expected 6 tools, got \${toolContracts.length}\`);
  if (names.size !== 6) throw new Error("tool names must be unique");
  if (operationIds.size !== 6) throw new Error("tool operationIds must be unique");
  for (const item of toolContracts) {
    if (!toolNames.includes(item.toolName)) throw new Error(\`\${item.toolName} is missing from toolNames\`);
    if (!toolOperationIds.includes(item.operationId)) throw new Error(\`\${item.operationId} is missing from toolOperationIds\`);
    if (!item.path.startsWith("/v1/tools/")) throw new Error(\`\${item.toolName} must live under /v1/tools/*\`);
    if (item.csrfRequired) throw new Error(\`\${item.toolName} must not require CSRF\`);
    if (!item.auditTable) throw new Error(\`\${item.toolName} must define audit table\`);
  }
  return true;
}
`;
}

function extractArray(source, name) {
  const start = source.indexOf(`export const ${name}`);
  assert(start >= 0, `missing ${name} export`);
  const bracketStart = source.indexOf("[", start);
  assert(bracketStart >= 0, `missing ${name} array`);
  return source.slice(bracketStart, findMatching(source, bracketStart, "[", "]") + 1);
}

function extractObject(source, name) {
  const start = source.indexOf(`export const ${name}`);
  assert(start >= 0, `missing ${name} export`);
  const objectStart = source.indexOf("{", start);
  assert(objectStart >= 0, `missing ${name} object`);
  return source.slice(objectStart, findMatching(source, objectStart, "{", "}") + 1);
}

function extractEntries(source, factoryName) {
  const entries = [];
  const entryPattern = new RegExp(`^  (${factoryName}\\(.*\\)),?$`, "gm");
  for (const match of source.matchAll(entryPattern)) {
    entries.push(`  ${match[1]}`);
  }
  return entries;
}

function findMatching(source, start, open, close) {
  let depth = 0;
  let quote = "";
  for (let index = start; index < source.length; index += 1) {
    const char = source[index];
    const previous = source[index - 1];
    if (quote) {
      if (char === quote && previous !== "\\") quote = "";
      continue;
    }
    if (char === "\"" || char === "'" || char === "`") {
      quote = char;
      continue;
    }
    if (char === open) depth += 1;
    if (char === close) depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error(`missing matching ${close}`);
}
