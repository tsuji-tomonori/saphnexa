import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
import { assert } from "./lib.js";

const check = process.argv.includes("--check");
const sourcePath = "apps/api/src/local-api.ts";
const outputPath = "apps/api/src/local-api.js";

const source = readFileSync(sourcePath, "utf8");
const generated = generateApiLocalRuntimeMirror(source);

if (check) {
  const current = readFileSync(outputPath, "utf8");
  assert(current === generated, "API local runtime mirror is out of date. Run npm run api:local:generate.");
} else {
  writeFileSync(outputPath, generated);
}

console.log(check ? "API local runtime mirror check passed" : "API local runtime mirror updated");

function generateApiLocalRuntimeMirror(tsSource) {
  const runtimeSource = ts
    .transpileModule(tsSource, {
      compilerOptions: {
        module: ts.ModuleKind.ES2022,
        target: ts.ScriptTarget.ES2022,
        importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
        removeComments: false
      },
      fileName: sourcePath
    })
    .outputText.replace(/from "(\.{1,2}\/[^"]+)(?<!\.js)"/gu, 'from "$1.js"')
    .trimEnd();

  assert(!runtimeSource.includes("import type "), "generated mirror must not include type-only imports");
  assert(!runtimeSource.includes("ApiOperationId"), "generated mirror must not include operation type annotations");
  assert(!runtimeSource.includes("LocalApiError"), "generated mirror must not include local error type annotations");
  assert(runtimeSource.includes("createLocalStore"), "generated mirror must create local store");
  assert(runtimeSource.includes("enforceCsrf"), "generated mirror must keep CSRF guard");
  assert(runtimeSource.includes("createFixtureRagAdapter"), "generated mirror must keep RAG adapter boundary");
  for (const operationId of ["getMe", "submitQuestion", "createDocument", "issueWsTicket", "consumeWsTicket"]) {
    assert(runtimeSource.includes(`case "${operationId}"`), `generated mirror missing ${operationId}`);
  }

  return `// Generated by tools/generate-api-local-runtime-mirror.js from ${sourcePath}. Do not edit by hand.

${runtimeSource}
`;
}
